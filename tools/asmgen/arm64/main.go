// Command arm64 generates the arm64 assembly of backend/cpu: the NEON GEMM
// micro-kernel.
//
//	go run ./arm64 -out ../../backend/cpu/gemm_arm64.s
//
// The Go assembler cannot encode FMLA by element, the instruction at the
// heart of the kernel, so the generator encodes it itself.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
)

func main() {
	out := flag.String("out", "", "file to write the assembly to")
	flag.Parse()
	var w bytes.Buffer
	fmt.Fprintf(&w, "// Code generated by command: go run ./arm64 -out ../../backend/cpu/gemm_arm64.s. DO NOT EDIT.\n\n")
	fmt.Fprintf(&w, "//go:build !purego\n\n#include \"textflag.h\"\n")
	tile(&w, "tileNEON", 8, 3)
	if err := os.WriteFile(*out, w.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// tile emits a micro-kernel computing an mr×(nv*4) tile with the signature
// and contract of gemmKernel.tile. Each step of the k loop loads mr
// elements of the packed A panel into mr/4 registers and nv vectors of the
// packed B panel, then multiplies each B vector by each A element into the
// accumulators, which take the registers from V8 up: mr*nv of them.
func tile(w *bytes.Buffer, name string, mr, nv int) {
	nr := 4 * nv
	if mr%4 != 0 || 8+mr*nv > 32 || mr/4+nv > 8 {
		log.Fatalf("%s: no registers for a %d×%d tile", name, mr, nr)
	}
	acc := func(i, j int) int { return 8 + i*nv + j }
	list := func(first, n int) string {
		var b bytes.Buffer
		for r := first; r < first+n; r++ {
			if r > first {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "V%d.S4", r)
		}
		return "[" + b.String() + "]"
	}
	emit := func(format string, args ...any) {
		fmt.Fprintf(w, "\t"+format+"\n", args...)
	}
	label := func(l string) { fmt.Fprintf(w, "\n%s_%s:\n", name, l) }

	fmt.Fprintf(w, "\n// %s computes one %d×%d tile; see gemmKernel.tile.\n", name, mr, nr)
	fmt.Fprintf(w, "//\n// func %s(kc int, a *float32, b *float32, c *float32, ldc int, accumulate bool)\n", name)
	fmt.Fprintf(w, "TEXT ·%s(SB), NOSPLIT, $0-41\n", name)
	emit("MOVD kc+0(FP), R0")
	emit("MOVD a+8(FP), R1")
	emit("MOVD b+16(FP), R2")
	emit("MOVD c+24(FP), R3")
	emit("MOVD ldc+32(FP), R4")
	emit("LSL $2, R4, R4")

	// Bring the output tile into cache while the products accumulate.
	emit("MOVD R3, R5")
	for i := range mr {
		emit("PRFM (R5), PLDL1KEEP")
		if i < mr-1 {
			emit("ADD R4, R5, R5")
		}
	}
	for i := range mr {
		for j := range nv {
			r := acc(i, j)
			emit("VEOR V%d.B16, V%d.B16, V%d.B16", r, r, r)
		}
	}
	emit("CBZ R0, %s_store", name)

	label("loop")
	emit("VLD1.P %d(R1), %s", 4*mr, list(0, mr/4))
	emit("VLD1.P %d(R2), %s", 4*nr, list(mr/4, nv))
	for i := range mr {
		for j := range nv {
			// FMLA acc.4S, B_j.4S, A_{i/4}.S[i%4]
			emit("WORD $0x%08x // FMLA V%d.4S, V%d.4S, V%d.S[%d]", fmlaElem(acc(i, j), mr/4+j, i/4, i%4), acc(i, j), mr/4+j, i/4, i%4)
		}
	}
	emit("SUBS $1, R0, R0")
	emit("BNE %s_loop", name)

	label("store")
	emit("MOVBU accumulate+40(FP), R5")
	emit("CBZ R5, %s_overwrite", name)
	for i := range mr {
		emit("VLD1 (R3), %s", list(0, nv))
		for j := range nv {
			emit("VFADD V%d.S4, V%d.S4, V%d.S4", j, acc(i, j), acc(i, j))
		}
		emit("VST1 %s, (R3)", list(acc(i, 0), nv))
		if i < mr-1 {
			emit("ADD R4, R3, R3")
		}
	}
	emit("RET")

	label("overwrite")
	for i := range mr {
		emit("VST1 %s, (R3)", list(acc(i, 0), nv))
		if i < mr-1 {
			emit("ADD R4, R3, R3")
		}
	}
	emit("RET")
}

// fmlaElem encodes FMLA Vd.4S, Vn.4S, Vm.S[idx], which adds the product of
// Vn and element idx of Vm to Vd.
func fmlaElem(d, n, m, idx int) uint32 {
	h, l := idx>>1, idx&1
	return 0x4f801000 | uint32(l)<<21 | uint32(m)<<16 | uint32(h)<<11 | uint32(n)<<5 | uint32(d)
}
