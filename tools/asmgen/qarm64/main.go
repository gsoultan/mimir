// Command qarm64 generates the arm64 assembly of backend/cpu's products by
// quantized weights: the NEON dot products of Q8_0, Q4_K and Q6_K weights
// with int8 activations, for one to four rows of activations, and, with
// SDOT, the tiles of Q4_K and Q6_K weights, two rows of them by sixteen
// rows of activations, that products of many rows of activations run in.
//
//	go run ./qarm64 -out ../../backend/cpu/qdot_arm64.s -stubs ../../backend/cpu/qdot_stub_arm64.go
//
// Each kernel comes in two forms: one that sums the products of four
// bytes at a time with SDOT, of the dot product extension that most
// cores since the Cortex-A55 and Apple's M1 have, and one for any NEON
// that multiplies with SMULL and sums pairs with ADDP and SADALP. Both
// leave lane i of a vector of four int32 the sum of the products of
// bytes 4i to 4i+3 of each 16, so they compute the same integers, and the
// float32 operations that apply the scales then run in the order of the
// portable kernels, one rounding each, without fused multiply-adds: every
// kernel matches qdotQ8_0Go, qdotQ4KGo or qdotQ6KGo bit for bit.
//
// The Go assembler encodes neither these instructions nor most vector
// arithmetic, so the generator encodes them itself.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
)

const maxRows = 4

func main() {
	out := flag.String("out", "", "file to write the assembly to")
	stubs := flag.String("stubs", "", "file to write the Go declarations to")
	flag.Parse()
	const header = "// Code generated by command: go run ./qarm64 -out ../../backend/cpu/qdot_arm64.s -stubs ../../backend/cpu/qdot_stub_arm64.go. DO NOT EDIT.\n\n//go:build !purego\n\n"
	var w bytes.Buffer
	w.WriteString(header + "#include \"textflag.h\"\n")
	for _, sdot := range []bool{true, false} {
		for rows := 1; rows <= maxRows; rows++ {
			q8_0(&w, rows, sdot)
			q4K(&w, rows, sdot)
			q6K(&w, rows, sdot)
		}
	}
	qtile(&w, false)
	qtile(&w, true)
	if err := os.WriteFile(*out, w.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	var g bytes.Buffer
	g.WriteString(header + "package cpu\n")
	for _, d := range decls {
		fmt.Fprintf(&g, "\n// %s\n//\n//go:noescape\nfunc %s%s\n", d.doc, d.name, d.sig)
	}
	if err := os.WriteFile(*stubs, g.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// decls are the functions generated, with their documentation and
// signatures.
var decls []decl

type decl struct{ name, doc, sig string }

// asm writes one function.
type asm struct {
	w    *bytes.Buffer
	name string
	sdot bool
}

func (a *asm) emit(format string, args ...any) { fmt.Fprintf(a.w, "\t"+format+"\n", args...) }

func (a *asm) word(enc uint32, format string, args ...any) {
	a.emit("WORD $0x%08x // %s", enc, fmt.Sprintf(format, args...))
}

func (a *asm) label(l string) { fmt.Fprintf(a.w, "\n%s_%s:\n", a.name, l) }

var rowsOf = [...]string{1: "one row", 2: "two rows", 3: "three rows", 4: "four rows"}

// begin writes the header of the kernel of dtype for rows rows and loads
// its arguments: nb into R0, w into R1, the rows of activations into R2
// to R5, out into R16 and ldo, in bytes, into R17.
func begin(w *bytes.Buffer, dtype string, rows int, sdot bool) *asm {
	ext := "NEON"
	if sdot {
		ext = "SDOT"
	}
	a := &asm{w: w, name: fmt.Sprintf("qdot%s%sx%d", dtype, ext, rows), sdot: sdot}
	doc := fmt.Sprintf("%s multiplies %s weights by %s of activations; see qdot.", a.name, dtype, rowsOf[rows])
	decls = append(decls, decl{a.name, doc, "(nb int, w *byte, x *byte, xstride int, out *float32, ldo int)"})
	fmt.Fprintf(w, "\n// %s\n", doc)
	fmt.Fprintf(w, "//\n// func %s(nb int, w *byte, x *byte, xstride int, out *float32, ldo int)\n", a.name)
	fmt.Fprintf(w, "TEXT ·%s(SB), NOSPLIT, $0-48\n", a.name)
	a.emit("MOVD nb+0(FP), R0")
	a.emit("MOVD w+8(FP), R1")
	a.emit("MOVD x+16(FP), R2")
	a.emit("MOVD xstride+24(FP), R6")
	for r := 1; r < rows; r++ {
		a.emit("ADD R6, R%d, R%d", 1+r, 2+r)
	}
	a.emit("MOVD out+32(FP), R16")
	a.emit("MOVD ldo+40(FP), R17")
	a.emit("LSL $2, R17, R17")
	return a
}

// store writes the float32 result of each row, in F8 up, to out.
func (a *asm) store(rows int) {
	for r := range rows {
		a.emit("FMOVS F%d, (R16)", 8+r)
		if r < rows-1 {
			a.emit("ADD R17, R16, R16")
		}
	}
	a.emit("RET")
}

// zero clears vector v.
func (a *asm) zero(v int) { a.emit("VEOR V%d.B16, V%d.B16, V%d.B16", v, v, v) }

// load32 loads the 32 bytes at off(base) into vectors v and v+1, through
// R6.
func (a *asm) load32(base string, off, v int) {
	a.emit("ADD $%d, %s, R6", off, base)
	a.emit("VLD1 (R6), [V%d.B16, V%d.B16]", v, v+1)
}

// half loads the float16 at off(R1) into Sd as a float32.
func (a *asm) half(off, d int) {
	a.emit("MOVHU %d(R1), R12", off)
	a.emit("FMOVS R12, F%d", d)
	a.emit("FCVTHS F%d, F%d", d, d)
}

// dot16 adds the products of the signed bytes of Vn and Vm, four at a
// time, to the int32 lanes of Vd: lane i gets bytes 4i to 4i+3. Without
// SDOT it uses V30 and V31.
func (a *asm) dot16(d, n, m int) {
	if a.sdot {
		a.word(0x4e809400|enc3(d, n, m), "SDOT V%d.4S, V%d.16B, V%d.16B", d, n, m)
		return
	}
	a.word(0x0e20c000|enc3(30, n, m), "SMULL V30.8H, V%d.8B, V%d.8B", n, m)
	a.word(0x4e20c000|enc3(31, n, m), "SMULL2 V31.8H, V%d.16B, V%d.16B", n, m)
	a.word(0x4e60bc00|enc3(30, 30, 31), "ADDP V30.8H, V30.8H, V31.8H")
	a.word(0x4e606800|enc3(d, 30, 0), "SADALP V%d.4S, V30.8H", d)
}

// enc3 places registers d, n and m in the fields of a vector instruction.
func enc3(d, n, m int) uint32 { return uint32(m)<<16 | uint32(n)<<5 | uint32(d) }

// Vector instructions, on all 16 bytes of a register.
func (a *asm) and(d, n, m int) {
	a.word(0x4e201c00|enc3(d, n, m), "AND V%d.16B, V%d.16B, V%d.16B", d, n, m)
}
func (a *asm) orr(d, n, m int) {
	a.word(0x4ea01c00|enc3(d, n, m), "ORR V%d.16B, V%d.16B, V%d.16B", d, n, m)
}
func (a *asm) subB(d, n, m int) {
	a.word(0x6e208400|enc3(d, n, m), "SUB V%d.16B, V%d.16B, V%d.16B", d, n, m)
}
func (a *asm) ushrB(d, n, s int) {
	a.word(0x6f000400|uint32(16-s)<<16|enc3(d, n, 0), "USHR V%d.16B, V%d.16B, #%d", d, n, s)
}
func (a *asm) shlB(d, n, s int) {
	a.word(0x4f005400|uint32(8+s)<<16|enc3(d, n, 0), "SHL V%d.16B, V%d.16B, #%d", d, n, s)
}

// moviB sets every byte of Vd to imm.
func (a *asm) moviB(d int, imm uint8) {
	a.word(0x4f00e400|uint32(imm>>5)<<16|uint32(imm&31)<<5|uint32(d), "MOVI V%d.16B, #%d", d, imm)
}

// mlaElem adds Vn times lane i of Vm to Vd, as int32s.
func (a *asm) mlaElem(d, n, m, i int) {
	a.word(0x6f800000|uint32(i&1)<<21|uint32(i>>1)<<11|enc3(d, n, m), "MLA V%d.4S, V%d.4S, V%d.S[%d]", d, n, m, i)
}

// addv sets Sd to the sum of the int32 lanes of Vn.
func (a *asm) addv(d, n int) { a.word(0x4eb1b800|enc3(d, n, 0), "ADDV S%d, V%d.4S", d, n) }

// scvtf converts the int32 in Sn to a float32 in Sd.
func (a *asm) scvtf(d, n int) { a.word(0x5e21d800|enc3(d, n, 0), "SCVTF S%d, S%d", d, n) }

// q8_0 emits the kernel of Q8_0 weights: blocks of a float16 scale and 32
// int8, by blocks of activations of a float32 scale and 32 int8. Row r
// keeps four float32 sums in V8+r, which it adds as (a0+a2)+(a1+a3).
func q8_0(w *bytes.Buffer, rows int, sdot bool) {
	a := begin(w, "Q8_0", rows, sdot)
	for r := range rows {
		a.zero(8 + r)
	}
	a.emit("CBZ R0, %s_done", a.name)
	a.label("loop")
	a.half(0, 16)
	a.load32("R1", 2, 20)
	for r := range rows {
		x := fmt.Sprintf("R%d", 2+r)
		a.load32(x, 4, 24)
		a.zero(26)
		a.dot16(26, 20, 24)
		a.dot16(26, 21, 25)
		a.word(0x4e21d800|enc3(26, 26, 0), "SCVTF V26.4S, V26.4S")
		a.emit("FMOVS (%s), F17", x)
		a.emit("FMULS F17, F16, F18")
		a.word(0x4f809000|enc3(26, 26, 18), "FMUL V26.4S, V26.4S, V18.S[0]")
		a.emit("VFADD V26.S4, V%d.S4, V%d.S4", 8+r, 8+r)
		a.emit("ADD $36, %s, %s", x, x)
	}
	a.emit("ADD $34, R1, R1")
	a.emit("SUBS $1, R0, R0")
	a.emit("BNE %s_loop", a.name)
	a.label("done")
	for r := range rows {
		a.word(0x6e004000|enc3(24, 8+r, 8+r), "EXT V24.16B, V%d.16B, V%d.16B, #8", 8+r, 8+r)
		a.emit("VFADD V24.S4, V%d.S4, V24.S4", 8+r)
		a.word(0x7e30d800|enc3(8+r, 24, 0), "FADDP S%d, V24.2S", 8+r)
	}
	a.store(rows)
}

// q4K emits the kernel of Q4_K weights by super-blocks of activations of
// a float32 scale, 256 int8 and the int16 sums of each 16. Row r sums the
// products times the scales in V0+r and the sums times the mins in V4+r,
// and keeps the float32 sums acc in F8+r and accm in F12+r.
func q4K(w *bytes.Buffer, rows int, sdot bool) {
	a := begin(w, "Q4_K", rows, sdot)
	for r := range rows {
		a.zero(8 + r)
		a.zero(12 + r)
	}
	a.moviB(28, 0x0f)
	a.emit("CBZ R0, %s_done", a.name)
	a.label("loop")
	// The scales and mins, unpacked as ggml's dot product unpacks them:
	// with u0, u1, u2 the three words of their 12 bytes,
	//
	//	scales = u0 & 0x3f3f3f3f | (u2 & 0x0f0f0f0f | (u0>>6 & 0x03030303)<<4) << 32
	//	mins   = u1 & 0x3f3f3f3f | (u2>>4 & 0x0f0f0f0f | (u1>>6 & 0x03030303)<<4) << 32
	//
	// then widened to int32s, scales in V16 and V17, mins in V18 and V19.
	a.emit("MOVWU 4(R1), R9")
	a.emit("MOVWU 8(R1), R10")
	a.emit("MOVWU 12(R1), R11")
	a.emit("LSRW $6, R9, R12")
	a.emit("ANDW $0x03030303, R12, R12")
	a.emit("ANDW $0x0f0f0f0f, R11, R13")
	a.emit("ORRW R12<<4, R13, R13")
	a.emit("ANDW $0x3f3f3f3f, R9, R14")
	a.emit("ORR R13<<32, R14, R14")
	a.emit("LSRW $6, R10, R12")
	a.emit("ANDW $0x03030303, R12, R12")
	a.emit("LSRW $4, R11, R13")
	a.emit("ANDW $0x0f0f0f0f, R13, R13")
	a.emit("ORRW R12<<4, R13, R13")
	a.emit("ANDW $0x3f3f3f3f, R10, R15")
	a.emit("ORR R13<<32, R15, R15")
	for _, v := range []int{16, 18} {
		src := "R14"
		if v == 18 {
			src = "R15"
		}
		a.emit("FMOVD %s, F%d", src, v)
		a.word(0x2f08a400|enc3(v, v, 0), "UXTL V%d.8H, V%d.8B", v, v)
		a.word(0x6f10a400|enc3(v+1, v, 0), "UXTL2 V%d.4S, V%d.8H", v+1, v)
		a.word(0x2f10a400|enc3(v, v, 0), "UXTL V%d.4S, V%d.4H", v, v)
	}
	a.half(0, 29) // d
	a.half(2, 27) // dmin
	for r := range rows {
		a.zero(r)
	}
	a.emit("ADD $16, R1, R7")
	for j := range 4 {
		// The 64 values 64j..64j+63: low nibbles in V20, V21 and high in
		// V22, V23, sub-blocks 2j and 2j+1.
		a.emit("VLD1.P 32(R7), [V20.B16, V21.B16]")
		a.ushrB(22, 20, 4)
		a.ushrB(23, 21, 4)
		a.and(20, 20, 28)
		a.and(21, 21, 28)
		for r := range rows {
			x := fmt.Sprintf("R%d", 2+r)
			a.emit("ADD $%d, %s, R6", 4+64*j, x)
			for s := range 2 {
				a.emit("VLD1.P 32(R6), [V24.B16, V25.B16]")
				a.zero(26)
				a.dot16(26, 20+2*s, 24)
				a.dot16(26, 21+2*s, 25)
				sub := 2*j + s
				a.mlaElem(r, 26, 16+sub/4, sub%4)
			}
		}
	}
	for r := range rows {
		x := fmt.Sprintf("R%d", 2+r)
		// The sums of each 32 activations, times the mins.
		a.emit("ADD $260, %s, R6", x)
		a.emit("VLD1 (R6), [V24.B16, V25.B16]")
		a.word(0x4e602800|enc3(24, 24, 0), "SADDLP V24.4S, V24.8H")
		a.word(0x4e602800|enc3(25, 25, 0), "SADDLP V25.4S, V25.8H")
		a.word(0x4ea09c00|enc3(4+r, 24, 18), "MUL V%d.4S, V24.4S, V18.4S", 4+r)
		a.word(0x4ea09400|enc3(4+r, 25, 19), "MLA V%d.4S, V25.4S, V19.4S", 4+r)
		a.addv(24, r)
		a.addv(25, 4+r)
		a.scvtf(24, 24)
		a.scvtf(25, 25)
		a.emit("FMOVS (%s), F26", x)
		a.emit("FMULS F26, F29, F30") // dd
		a.emit("FMULS F26, F27, F31") // dm
		a.emit("FMULS F24, F30, F24")
		a.emit("FADDS F24, F%d, F%d", 8+r, 8+r)
		a.emit("FMULS F25, F31, F25")
		a.emit("FADDS F25, F%d, F%d", 12+r, 12+r)
		a.emit("ADD $292, %s, %s", x, x)
	}
	a.emit("ADD $144, R1, R1")
	a.emit("SUBS $1, R0, R0")
	a.emit("BNE %s_loop", a.name)
	a.label("done")
	for r := range rows {
		a.emit("FSUBS F%d, F%d, F%d", 12+r, 8+r, 8+r)
	}
	a.store(rows)
}

// q6K emits the kernel of Q6_K weights by super-blocks of activations.
// The quants, less 32, multiply as signed bytes, so the activations' sums
// go unused. Row r sums the products times the scales in V0+r and keeps
// its float32 sum in F8+r.
func q6K(w *bytes.Buffer, rows int, sdot bool) {
	a := begin(w, "Q6_K", rows, sdot)
	for r := range rows {
		a.zero(8 + r)
	}
	a.moviB(28, 0x0f)
	a.moviB(29, 0x30)
	a.moviB(27, 32)
	a.emit("CBZ R0, %s_done", a.name)
	a.label("loop")
	// The scales of the 16 groups as int32s: groups 4i to 4i+3 in V16+i.
	a.emit("ADD $192, R1, R6")
	a.emit("VLD1 (R6), [V16.B16]")
	a.word(0x4f08a400|enc3(18, 16, 0), "SXTL2 V18.8H, V16.16B")
	a.word(0x0f08a400|enc3(16, 16, 0), "SXTL V16.8H, V16.8B")
	a.word(0x4f10a400|enc3(19, 18, 0), "SXTL2 V19.4S, V18.8H")
	a.word(0x0f10a400|enc3(18, 18, 0), "SXTL V18.4S, V18.4H")
	a.word(0x4f10a400|enc3(17, 16, 0), "SXTL2 V17.4S, V16.8H")
	a.word(0x0f10a400|enc3(16, 16, 0), "SXTL V16.4S, V16.4H")
	a.half(208, 14) // d
	for r := range rows {
		a.zero(r)
	}
	for n := range 2 {
		// The half's 64 bytes of low bits in V4 to V7, 32 of high in V12
		// and V13.
		a.emit("ADD $%d, R1, R6", 64*n)
		a.emit("VLD1 (R6), [V4.B16, V5.B16, V6.B16, V7.B16]")
		a.emit("ADD $%d, R1, R6", 128+32*n)
		a.emit("VLD1 (R6), [V12.B16, V13.B16]")
		for k := range 4 {
			// Values 128n+32k+16h+l, l < 16, in V20+h: 4 bits of the
			// low byte and 2 of the high, less 32.
			for h := range 2 {
				q, lo, hi := 20+h, 4+2*(k%2)+h, 12+h
				if k < 2 {
					a.and(q, lo, 28)
				} else {
					a.ushrB(q, lo, 4)
				}
				switch k {
				case 0:
					a.shlB(23, hi, 4)
				case 1:
					a.shlB(23, hi, 2)
				case 2:
					a.and(23, hi, 29)
				case 3:
					a.ushrB(23, hi, 2)
				}
				if k != 2 {
					a.and(23, 23, 29)
				}
				a.orr(q, q, 23)
				a.subB(q, q, 27)
			}
			g := 8*n + 2*k
			for r := range rows {
				a.emit("ADD $%d, R%d, R6", 4+128*n+32*k, 2+r)
				a.emit("VLD1 (R6), [V24.B16, V25.B16]")
				for h := range 2 {
					a.zero(26)
					a.dot16(26, 20+h, 24+h)
					a.mlaElem(r, 26, 16+(g+h)/4, (g+h)%4)
				}
			}
		}
	}
	for r := range rows {
		x := fmt.Sprintf("R%d", 2+r)
		a.addv(24, r)
		a.scvtf(24, 24)
		a.emit("FMOVS (%s), F25", x)
		a.emit("FMULS F25, F14, F25") // dd
		a.emit("FMULS F24, F25, F24")
		a.emit("FADDS F24, F%d, F%d", 8+r, 8+r)
		a.emit("ADD $292, %s, %s", x, x)
	}
	a.emit("ADD $210, R1, R1")
	a.emit("SUBS $1, R0, R0")
	a.emit("BNE %s_loop", a.name)
	a.label("done")
	a.store(rows)
}

// The layouts of backend/cpu's tiles: a super-block of a row of weights,
// unpacked, and one of sixteen rows of activations, interleaved.
const (
	tileRowBytes = 336
	tileScales   = 256 // [16]int16
	tilePairs    = 288 // [8][2]int16
	tileD        = 320 // float32, and dmin after it
	tileActBytes = 4672
	tileSums     = 4096 // [8][16][2]int16
	tileXD       = 4608 // [16]float32
)

// qtile emits the tile kernel of Q4_K weights, or of Q6_K weights if q6,
// for two rows of weights by sixteen of activations, with SDOT by
// element: a vector holds four quants of each of four rows of
// activations, and SDOT adds their products with four quants of a row of
// weights, one lane of a vector of sixteen, into an int32 for each row.
// The sums of a group, in V8 to V15, are added times the group's scale to
// those of the super-block, V0 to V3 for the first row of weights and V4
// to V7 for the second; the quants of Q6_K, less 32, multiply as signed
// bytes, so that the activations' sums apply only the mins of Q4_K.
//
// It loads nb into R0, the weights into R1, the activations into R2 and
// acc into R3.
func qtile(w *bytes.Buffer, q6 bool) {
	dtype, group := "Q4_K", 32
	if q6 {
		dtype, group = "Q6_K", 16
	}
	a := &asm{w: w, name: "qtile" + dtype + "SDOT", sdot: true}
	doc := a.name + " multiplies two rows of unpacked weights by sixteen rows of interleaved activations; see qtile."
	const sig = "(nb int, w *byte, x *byte, acc *float32)"
	decls = append(decls, decl{a.name, doc, sig})
	fmt.Fprintf(w, "\n// %s\n", doc)
	fmt.Fprintf(w, "//\n// func %s%s\n", a.name, sig)
	fmt.Fprintf(w, "TEXT ·%s(SB), NOSPLIT, $0-32\n", a.name)
	a.emit("MOVD nb+0(FP), R0")
	a.emit("MOVD w+8(FP), R1")
	a.emit("MOVD x+16(FP), R2")
	a.emit("MOVD acc+24(FP), R3")
	if q6 {
		a.moviB(30, 32)
	}
	a.emit("CBZ R0, %s_done", a.name)
	a.label("loop")

	// The scales as int32s: four groups a vector, from V22 for the first
	// row of weights and from V22+groups/4 for the second.
	nsc := 256 / group / 4
	for t := range 2 {
		b := 22 + nsc*t
		a.emit("ADD $%d, R1, R6", tileRowBytes*t+tileScales)
		if q6 {
			a.emit("VLD1 (R6), [V%d.B16, V%d.B16]", b, b+1)
			a.word(0x4f10a400|enc3(b+3, b+1, 0), "SXTL2 V%d.4S, V%d.8H", b+3, b+1)
			a.word(0x0f10a400|enc3(b+2, b+1, 0), "SXTL V%d.4S, V%d.4H", b+2, b+1)
		} else {
			a.emit("VLD1 (R6), [V%d.B16]", b)
		}
		a.word(0x4f10a400|enc3(b+1, b, 0), "SXTL2 V%d.4S, V%d.8H", b+1, b)
		a.word(0x0f10a400|enc3(b, b, 0), "SXTL V%d.4S, V%d.4H", b, b)
	}
	for v := range 8 {
		a.zero(v)
	}
	a.emit("MOVD R2, R7")
	a.emit("MOVD R1, R8")
	a.emit("ADD $%d, R1, R9", tileRowBytes)
	for s := range 256 / group {
		for v := 8; v < 16; v++ {
			a.zero(v)
		}
		for q := range group / 4 {
			quad := group/4*s + q
			if quad%4 == 0 {
				// The next four quads of quants of each row of weights.
				for t := range 2 {
					a.emit("VLD1.P 16(R%d), [V%d.B16]", 8+t, 20+t)
					if q6 {
						a.subB(20+t, 20+t, 30)
					}
				}
			}
			a.emit("VLD1.P 64(R7), [V16.B16, V17.B16, V18.B16, V19.B16]")
			for t := range 2 {
				for c := range 4 {
					d, n, m, i := 8+4*t+c, 16+c, 20+t, quad%4
					a.word(0x4f80e000|uint32(i&1)<<21|uint32(i>>1)<<11|enc3(d, n, m),
						"SDOT V%d.4S, V%d.16B, V%d.4B[%d]", d, n, m, i)
				}
			}
		}
		for t := range 2 {
			for c := range 4 {
				a.mlaElem(4*t+c, 8+4*t+c, 22+nsc*t+s/4, s%4)
			}
		}
	}

	for t := range 2 {
		if !q6 {
			// The sums of the activations' pairs of groups of 16 times
			// the mins: lanes of pairs of int32 in V8 to V15, which
			// ADDP adds into V8 to V11.
			a.emit("ADD $%d, R2, R7", tileSums)
			for p := range 8 {
				a.emit("MOVWU %d(R1), R10", tileRowBytes*t+tilePairs+4*p)
				a.word(0x4e040c00|enc3(20, 10, 0), "DUP V20.4S, R10")
				a.emit("VLD1.P 64(R7), [V16.B16, V17.B16, V18.B16, V19.B16]")
				for c := range 4 {
					lo, hi := 0x0e608000, 0x4e608000
					name := "SMLAL"
					if p == 0 {
						lo, hi, name = 0x0e60c000, 0x4e60c000, "SMULL"
					}
					a.word(uint32(lo)|enc3(8+2*c, 16+c, 20), "%s V%d.4S, V%d.4H, V20.4H", name, 8+2*c, 16+c)
					a.word(uint32(hi)|enc3(9+2*c, 16+c, 20), "%s2 V%d.4S, V%d.8H, V20.8H", name, 9+2*c, 16+c)
				}
			}
			for c := range 4 {
				a.word(0x4ea0bc00|enc3(8+c, 8+2*c, 9+2*c), "ADDP V%d.4S, V%d.4S, V%d.4S", 8+c, 8+2*c, 9+2*c)
			}
		}
		// The products times float32(wd·xd), added to acc.
		a.emit("ADD $%d, R2, R7", tileXD)
		a.emit("VLD1 (R7), [V16.B16, V17.B16, V18.B16, V19.B16]")
		a.emit("FMOVS %d(R1), F20", tileRowBytes*t+tileD)
		a.emit("FMOVS %d(R1), F21", tileRowBytes*t+tileD+4)
		a.emit("ADD $%d, R3, R7", 4*16*t)
		a.emit("VLD1 (R7), [V24.B16, V25.B16, V26.B16, V27.B16]")
		for c := range 4 {
			a.accumulate(24+c, 4*t+c, 16+c, 20)
		}
		a.emit("VST1 [V24.B16, V25.B16, V26.B16, V27.B16], (R7)")
		if !q6 {
			a.emit("ADD $%d, R3, R7", 4*(32+16*t))
			a.emit("VLD1 (R7), [V24.B16, V25.B16, V26.B16, V27.B16]")
			for c := range 4 {
				a.accumulate(24+c, 8+c, 16+c, 21)
			}
			a.emit("VST1 [V24.B16, V25.B16, V26.B16, V27.B16], (R7)")
		}
	}
	a.emit("ADD $%d, R1, R1", 2*tileRowBytes)
	a.emit("MOVD $%d, R10", tileActBytes)
	a.emit("ADD R10, R2, R2")
	a.emit("SUBS $1, R0, R0")
	a.emit("BNE %s_loop", a.name)
	a.label("done")
	a.emit("RET")
}

// accumulate adds float32(wd·xd)·float32(sum) to the four float32 of Vacc,
// rounding each product, as the portable kernels do: sum is in Vsum, xd in
// Vxd and wd in lane 0 of Vwd. It uses V28 and V29.
func (a *asm) accumulate(acc, sum, xd, wd int) {
	a.word(0x4f809000|enc3(28, xd, wd), "FMUL V28.4S, V%d.4S, V%d.S[0]", xd, wd)
	a.word(0x4e21d800|enc3(29, sum, 0), "SCVTF V29.4S, V%d.4S", sum)
	a.word(0x6e20dc00|enc3(29, 29, 28), "FMUL V29.4S, V29.4S, V28.4S")
	a.emit("VFADD V29.S4, V%d.S4, V%d.S4", acc, acc)
}
